-- Glossary of Turkish identifiers
--   Tables : GIB_EBELGE e-invoice register at the tax authority · KURAL_ORAN valid VAT rates ·
--            KURAL_ESKI_ORAN old rate → new rate · KURAL_SINIR withholding threshold by year ·
--            KURAL_TEVKIFAT withholding types · KURAL_PARAMETRE check parameters · SIRKET_VERGI company tax profile
--   Columns: BELGE_NO invoice no. · YON direction (GIDEN outgoing, GELEN incoming) · BELGE_TURU document type ·
--            SENARYO profile · TIP type · DURUM status · GONDEREN sender · ALICI receiver (in KURAL_TEVKIFAT: buyer scope) ·
--            UNVAN name · BELGE_TARIHI invoice date · PARA currency · MATRAH tax base · KDV_ORANI VAT rate ·
--            KDV_TUTARI VAT amount · TEVKIFAT withholding · ISTISNA_KODU exemption code · GECERLI_BAS valid from ·
--            ORAN rate · YIL year · SINIR_KDV_DAHIL threshold incl. VAT · AD name · PAY/PAYDA numerator/denominator ·
--            BOLUM communiqué section · DEGER value · VKN tax number · KDV_MUKELLEFI VAT-registered ·
--            BELIRLENMIS_ALICI designated buyer
--   Results: KURAL rule · GUVEN confidence · TUR type · MUHATAP counterparty · KAYIT_TARIHI posting date ·
--            ETKI_* correction · DEFTER ledger · GIB tax authority · DETAY detail · HES output VAT · IND input VAT ·
--            TEV withholding · KODSUZ without a tax code · MAHSUP VAT offset entry · ULKE country · DONEM period ·
--            HESAPLANAN output VAT · INDIRILECEK input VAT · SORUMLU VAT declared as responsible party (KDV2) ·
--            BEYANNAME return · FARK difference · LT_ / LV_ local table / local variable
--   Functions: TF_BELGELER documents · TF_K1_EBELGE e-invoice ↔ ledger · TF_K2_MUKERRER duplicates ·
--            TF_K3_ORAN rate · TF_K4_TEVKIFAT withholding · TF_K5_DONEM period · TF_K6_KODSUZ no tax code ·
--            TF_KONTROLLER all checks · TF_BEYANNAME_AYLIK monthly return · TF_MUTABAKAT reconciliation ·
--            TF_TOPLAM_KONTROLU totals-only check
--
-- Örnek Makine A.Ş. — VAT check engine, schema VERGI (SQLScript table functions).
-- Every check takes two parameters: IV_DONEM (period, 'YYYYMM') and IV_GUN (as-of date, 'YYYYMMDD').
-- Only documents posted and e-invoices received by the evening of IV_GUN are visible:
-- the engine never sees the future, which is what the back-test relies on.
-- A finding row: KURAL (rule), GUVEN (confidence: KESIN certain / MUHTEMEL medium / ZAYIF weak), TUR (RISK / FIRSAT opportunity), document,
-- ETKI_HES / ETKI_IND / ETKI_KDV2 = corrected − as booked (TRY): output VAT, input VAT, KDV2.
-- Statements are separated by a "-- @@" line.

-- Tax summary per document: direction, counterparty, VAT in the ledger (191/391), tax lines (BSET), withholding.
CREATE FUNCTION TF_BELGELER (IV_GUN NVARCHAR(8))
RETURNS TABLE (BELNR NVARCHAR(10), GJAHR NVARCHAR(4), BLART NVARCHAR(2), BLDAT NVARCHAR(8), BUDAT NVARCHAR(8),
               XBLNR NVARCHAR(16), YON NVARCHAR(5), MUHATAP NVARCHAR(10), ULKE NVARCHAR(3), NACE NVARCHAR(4),
               KDV_DEFTER DECIMAL(23,2), HES DECIMAL(23,2), IND DECIMAL(23,2), MATRAH DECIMAL(23,2),
               BSET_SATIR INTEGER, MWSKZ NVARCHAR(2), TEV_KODU NVARCHAR(2), TEV_TUTAR DECIMAL(23,2),
               KODSUZ_191 DECIMAL(23,2), KODSUZ_391 DECIMAL(23,2), MAHSUP INTEGER)
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  LT_S = SELECT a.BELNR, a.GJAHR, MAX(a.BUDAT) AS BUDAT, MAX(a.BLDAT) AS BLDAT, MAX(a.BLART) AS BLART,
                MAX(CASE WHEN a.KUNNR <> '' THEN a.KUNNR END) AS KUNNR,
                MAX(CASE WHEN a.LIFNR <> '' THEN a.LIFNR END) AS LIFNR,
                SUM(CASE WHEN a.RACCT = '1910000001' THEN a.HSL ELSE 0 END) AS T191,
                SUM(CASE WHEN a.RACCT = '3910000001' THEN -a.HSL ELSE 0 END) AS T391,
                SUM(CASE WHEN a.RACCT = '1910000001' AND a.MWSKZ = '' THEN a.HSL ELSE 0 END) AS K191,
                SUM(CASE WHEN a.RACCT = '3910000001' AND a.MWSKZ = '' THEN -a.HSL ELSE 0 END) AS K391,
                MIN(CASE WHEN a.RACCT IN ('1910000001', '3910000001') OR a.RACCT LIKE '360%' THEN 1 ELSE 0 END) AS MAHSUP
           FROM ACDOCA a
          WHERE a.RCLNT = '100' AND a.RLDNR = '0L' AND a.RBUKRS = '1000' AND a.BUDAT <= :IV_GUN
          GROUP BY a.BELNR, a.GJAHR;
  LT_V = SELECT BELNR, GJAHR,
                SUM(CASE WHEN KTOSL = 'MWS' THEN CASE SHKZG WHEN 'H' THEN HWSTE ELSE -HWSTE END ELSE 0 END) AS HES,
                SUM(CASE WHEN KTOSL = 'VST' THEN CASE SHKZG WHEN 'S' THEN HWSTE ELSE -HWSTE END ELSE 0 END) AS IND,
                SUM(HWBAS) AS MATRAH, COUNT(*) AS N, MAX(MWSKZ) AS MWSKZ
           FROM BSET WHERE MANDT = '100' AND BUKRS = '1000' GROUP BY BELNR, GJAHR;
  LT_W = SELECT BELNR, GJAHR, MAX(WT_WITHCD) AS KOD, SUM(WT_QBSHH) AS TUTAR
           FROM WITH_ITEM WHERE MANDT = '100' AND BUKRS = '1000' AND WITHT = 'KT' GROUP BY BELNR, GJAHR;
  RETURN
    SELECT s.BELNR, s.GJAHR, s.BLART, s.BLDAT, s.BUDAT, k.XBLNR,
           CAST(CASE WHEN s.KUNNR IS NOT NULL THEN 'GIDEN' WHEN s.LIFNR IS NOT NULL THEN 'GELEN'
                     WHEN COALESCE(v.IND, 0) <> 0 OR s.K191 > 0 OR (s.T191 > 0 AND s.MAHSUP = 0) THEN 'GELEN'
                     ELSE '' END AS NVARCHAR(5)) AS YON,
           COALESCE(s.KUNNR, s.LIFNR, '') AS MUHATAP,
           COALESCE(m.LAND1, l.LAND1, '') AS ULKE, COALESCE(l.BRSCH, '') AS NACE,
           CASE WHEN s.KUNNR IS NOT NULL THEN s.T391 ELSE s.T191 END AS KDV_DEFTER,
           COALESCE(v.HES, 0) AS HES, COALESCE(v.IND, 0) AS IND, COALESCE(v.MATRAH, 0) AS MATRAH,
           COALESCE(v.N, 0) AS BSET_SATIR, COALESCE(v.MWSKZ, '') AS MWSKZ,
           COALESCE(w.KOD, '') AS TEV_KODU, COALESCE(w.TUTAR, 0) AS TEV_TUTAR,
           s.K191 AS KODSUZ_191, s.K391 AS KODSUZ_391, s.MAHSUP
      FROM :LT_S s
      JOIN BKPF k ON k.MANDT = '100' AND k.BUKRS = '1000' AND k.BELNR = s.BELNR AND k.GJAHR = s.GJAHR
      LEFT JOIN :LT_V v ON v.BELNR = s.BELNR AND v.GJAHR = s.GJAHR
      LEFT JOIN :LT_W w ON w.BELNR = s.BELNR AND w.GJAHR = s.GJAHR
      LEFT JOIN KNA1 m ON m.MANDT = '100' AND m.KUNNR = s.KUNNR
      LEFT JOIN LFA1 l ON l.MANDT = '100' AND l.LIFNR = s.LIFNR;
END
