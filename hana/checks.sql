-- K5 · Tax period. A sales invoice in its own month; purchase VAT within the VAT Law 29/3 time limit.
CREATE FUNCTION TF_K5_DONEM (IV_DONEM NVARCHAR(6), IV_GUN NVARCHAR(8))
RETURNS TABLE (KURAL NVARCHAR(30), GUVEN NVARCHAR(8), TUR NVARCHAR(6), BELNR NVARCHAR(10), GJAHR NVARCHAR(4),
               XBLNR NVARCHAR(16), ETTN NVARCHAR(36), MUHATAP NVARCHAR(10), BELGE_TARIHI NVARCHAR(8),
               KAYIT_TARIHI NVARCHAR(8), ETKI_HES DECIMAL(23,2), ETKI_IND DECIMAL(23,2), ETKI_KDV2 DECIMAL(23,2),
               DEFTER_DEGER DECIMAL(23,2), GIB_DEGER DECIMAL(23,2), DETAY NVARCHAR(100))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  DECLARE LV_YIL INTEGER;
  SELECT TO_INT(DEGER) INTO LV_YIL FROM KURAL_PARAMETRE WHERE AD = 'INDIRIM_SURESI_YIL';
  LT_B = SELECT * FROM TF_BELGELER(:IV_GUN);
  RETURN
    -- (a) a sale of this period posted in a later month: this period's return is short
    SELECT CAST('K5_SATIS_GEC' AS NVARCHAR(30)) AS KURAL, CAST('KESIN' AS NVARCHAR(8)) AS GUVEN,
           CAST('RISK' AS NVARCHAR(6)) AS TUR, b.BELNR, b.GJAHR, b.XBLNR, CAST('' AS NVARCHAR(36)) AS ETTN,
           b.MUHATAP, b.BLDAT AS BELGE_TARIHI, b.BUDAT AS KAYIT_TARIHI, b.HES AS ETKI_HES,
           TO_DECIMAL(0, 23, 2) AS ETKI_IND, TO_DECIMAL(0, 23, 2) AS ETKI_KDV2, TO_DECIMAL(0, 23, 2) AS DEFTER_DEGER,
           b.HES AS GIB_DEGER, CAST(LEFT(b.BUDAT, 6) AS NVARCHAR(100)) AS DETAY
      FROM :LT_B b
     WHERE b.YON = 'GIDEN' AND LEFT(b.BLDAT, 6) = :IV_DONEM AND LEFT(b.BUDAT, 6) > :IV_DONEM AND b.HES <> 0
    UNION ALL
    -- (b) a sale of an earlier period posted in this one: declared extra in this period
    SELECT 'K5_SATIS_GEC', 'KESIN', 'FIRSAT', b.BELNR, b.GJAHR, b.XBLNR, '', b.MUHATAP, b.BLDAT, b.BUDAT,
           -b.HES, 0, 0, b.HES, 0, LEFT(b.BLDAT, 6)
      FROM :LT_B b
     WHERE b.YON = 'GIDEN' AND LEFT(b.BUDAT, 6) = :IV_DONEM AND LEFT(b.BLDAT, 6) < :IV_DONEM AND b.HES <> 0
    UNION ALL
    -- (c) deduction time limit passed: deducted after the end of the year following the invoice year
    SELECT 'K5_SURESI_GECMIS', 'KESIN', 'RISK', b.BELNR, b.GJAHR, b.XBLNR, '', b.MUHATAP, b.BLDAT, b.BUDAT,
           0, -b.IND, 0, b.IND, 0, LEFT(b.BLDAT, 4)
      FROM :LT_B b
     WHERE b.YON = 'GELEN' AND LEFT(b.BUDAT, 6) = :IV_DONEM AND b.IND > 0
       AND TO_INT(LEFT(b.BUDAT, 4)) - TO_INT(LEFT(b.BLDAT, 4)) > :LV_YIL;
END
