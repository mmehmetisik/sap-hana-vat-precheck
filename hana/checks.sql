-- K2 · Duplicate invoice
CREATE FUNCTION TF_K2_MUKERRER (IV_DONEM NVARCHAR(6), IV_GUN NVARCHAR(8))
RETURNS TABLE (KURAL NVARCHAR(30), GUVEN NVARCHAR(8), TUR NVARCHAR(6), BELNR NVARCHAR(10), GJAHR NVARCHAR(4),
               XBLNR NVARCHAR(16), ETTN NVARCHAR(36), MUHATAP NVARCHAR(10), BELGE_TARIHI NVARCHAR(8),
               KAYIT_TARIHI NVARCHAR(8), ETKI_HES DECIMAL(23,2), ETKI_IND DECIMAL(23,2), ETKI_KDV2 DECIMAL(23,2),
               DEFTER_DEGER DECIMAL(23,2), GIB_DEGER DECIMAL(23,2), DETAY NVARCHAR(100))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  DECLARE LV_GUN INTEGER;
  SELECT TO_INT(DEGER) INTO LV_GUN FROM KURAL_PARAMETRE WHERE AD = 'MUKERRER_GUN';
  LT_B = SELECT * FROM TF_BELGELER(:IV_GUN) WHERE YON = 'GELEN' AND XBLNR <> '' AND MATRAH > 0;
  LT_G = SELECT BELGE_NO, MAX(ETTN) AS ETTN, MAX(CASE WHEN DURUM = 'GECERLI' THEN 1 ELSE 0 END) AS GECERLI
           FROM GIB_EBELGE WHERE YON = 'GELEN' AND BELGE_TARIHI <= :IV_GUN GROUP BY BELGE_NO;
  LT_A = SELECT b.BELNR, b.GJAHR, b.XBLNR, b.MUHATAP, b.BLDAT, b.BUDAT, b.IND, b.KDV_DEFTER,
                ROW_NUMBER() OVER (PARTITION BY b.MUHATAP, b.XBLNR ORDER BY b.BUDAT, b.GJAHR, b.BELNR) AS SIRA,
                FIRST_VALUE(b.BELNR) OVER (PARTITION BY b.MUHATAP, b.XBLNR ORDER BY b.BUDAT, b.GJAHR, b.BELNR) AS ILK
           FROM :LT_B b;
  -- same vendor, same base, close dates, different numbers: x is the later, y the earlier document
  LT_C = SELECT x.BELNR, x.GJAHR, x.XBLNR, x.MUHATAP, x.BLDAT, x.BUDAT, x.IND, x.KDV_DEFTER,
                MIN(y.BELNR) AS Y_BELNR, MAX(COALESCE(gx.GECERLI, -1)) AS X_GIB, MIN(COALESCE(gy.GECERLI, -1)) AS Y_GIB,
                MAX(gx.ETTN) AS ETTN
           FROM :LT_B x
           JOIN :LT_B y ON y.MUHATAP = x.MUHATAP AND y.MATRAH = x.MATRAH AND y.XBLNR <> x.XBLNR
                       AND (y.BLDAT < x.BLDAT OR (y.BLDAT = x.BLDAT AND y.GJAHR || y.BELNR < x.GJAHR || x.BELNR))
                       AND DAYS_BETWEEN(TO_DATE(y.BLDAT, 'YYYYMMDD'), TO_DATE(x.BLDAT, 'YYYYMMDD')) <= :LV_GUN
           LEFT JOIN :LT_G gx ON gx.BELGE_NO = x.XBLNR
           LEFT JOIN :LT_G gy ON gy.BELGE_NO = y.XBLNR
          WHERE LEFT(x.BUDAT, 6) = :IV_DONEM
          GROUP BY x.BELNR, x.GJAHR, x.XBLNR, x.MUHATAP, x.BLDAT, x.BUDAT, x.IND, x.KDV_DEFTER;
  RETURN
    -- (a) same vendor, same invoice number: all but the first are extra
    SELECT CAST('K2_MUKERRER' AS NVARCHAR(30)) AS KURAL, CAST('KESIN' AS NVARCHAR(8)) AS GUVEN,
           CAST('RISK' AS NVARCHAR(6)) AS TUR, a.BELNR, a.GJAHR, a.XBLNR, COALESCE(g.ETTN, '') AS ETTN, a.MUHATAP,
           a.BLDAT AS BELGE_TARIHI, a.BUDAT AS KAYIT_TARIHI, TO_DECIMAL(0, 23, 2) AS ETKI_HES, -a.IND AS ETKI_IND,
           TO_DECIMAL(0, 23, 2) AS ETKI_KDV2, a.KDV_DEFTER AS DEFTER_DEGER, TO_DECIMAL(0, 23, 2) AS GIB_DEGER,
           CAST(a.ILK AS NVARCHAR(100)) AS DETAY
      FROM :LT_A a LEFT JOIN :LT_G g ON g.BELGE_NO = a.XBLNR
     WHERE a.SIRA > 1 AND LEFT(a.BUDAT, 6) = :IV_DONEM
    UNION ALL
    -- (b) one is not at the tax authority: possibly posted twice with the number retyped
    SELECT 'K2_MUHTEMEL_MUKERRER', 'MUHTEMEL', 'RISK', c.BELNR, c.GJAHR, c.XBLNR, '', c.MUHATAP, c.BLDAT, c.BUDAT,
           0, -c.IND, 0, c.KDV_DEFTER, 0, c.Y_BELNR
      FROM :LT_C c WHERE c.X_GIB = -1 AND c.Y_GIB >= 0
    UNION ALL
    -- (c) both valid at the tax authority: the vendor may have billed one delivery twice
    SELECT 'K2_AYNI_TUTAR', 'ZAYIF', 'RISK', c.BELNR, c.GJAHR, c.XBLNR, COALESCE(c.ETTN, ''), c.MUHATAP, c.BLDAT,
           c.BUDAT, 0, -c.IND, 0, c.KDV_DEFTER, 0, c.Y_BELNR
      FROM :LT_C c WHERE c.X_GIB = 1 AND c.Y_GIB = 1;
END
