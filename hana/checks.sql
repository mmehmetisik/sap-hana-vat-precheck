-- Month-end reconciliation: movements on 191/391 vs. the tax lines that reach the return (VAT offset excluded).
CREATE FUNCTION TF_MUTABAKAT (IV_DONEM NVARCHAR(6), IV_GUN NVARCHAR(8))
RETURNS TABLE (HESAP NVARCHAR(10), DEFTER DECIMAL(23,2), BEYANNAME DECIMAL(23,2), FARK DECIMAL(23,2))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  LT_B = SELECT * FROM TF_BELGELER(:IV_GUN) WHERE LEFT(BUDAT, 6) = :IV_DONEM AND MAHSUP = 0;
  RETURN
    SELECT CAST('1910000001' AS NVARCHAR(10)) AS HESAP,
           SUM(CASE WHEN YON = 'GELEN' THEN KDV_DEFTER ELSE 0 END) AS DEFTER, SUM(IND) AS BEYANNAME,
           SUM(CASE WHEN YON = 'GELEN' THEN KDV_DEFTER ELSE 0 END) - SUM(IND) AS FARK
      FROM :LT_B
    UNION ALL
    SELECT '3910000001', SUM(CASE WHEN YON = 'GIDEN' THEN KDV_DEFTER ELSE 0 END), SUM(HES),
           SUM(CASE WHEN YON = 'GIDEN' THEN KDV_DEFTER ELSE 0 END) - SUM(HES)
      FROM :LT_B;
END
