-- K3 · Rate and tax code. The code's rate comes from A003 → KONP (KBETR in per mille); valid rates in KURAL_ORAN.
CREATE FUNCTION TF_K3_ORAN (IV_DONEM NVARCHAR(6), IV_GUN NVARCHAR(8))
RETURNS TABLE (KURAL NVARCHAR(30), GUVEN NVARCHAR(8), TUR NVARCHAR(6), BELNR NVARCHAR(10), GJAHR NVARCHAR(4),
               XBLNR NVARCHAR(16), ETTN NVARCHAR(36), MUHATAP NVARCHAR(10), BELGE_TARIHI NVARCHAR(8),
               KAYIT_TARIHI NVARCHAR(8), ETKI_HES DECIMAL(23,2), ETKI_IND DECIMAL(23,2), ETKI_KDV2 DECIMAL(23,2),
               DEFTER_DEGER DECIMAL(23,2), GIB_DEGER DECIMAL(23,2), DETAY NVARCHAR(100))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  DECLARE LV_TOL DECIMAL(23,2);
  DECLARE LV_GENEL DECIMAL(5,2);
  SELECT DEGER INTO LV_TOL FROM KURAL_PARAMETRE WHERE AD = 'TOLERANS_TL';
  SELECT DEGER INTO LV_GENEL FROM KURAL_PARAMETRE WHERE AD = 'GENEL_ORAN';
  LT_ORAN = SELECT a.MWSKZ, p.KBETR / 10 AS ORAN
              FROM A003 a JOIN KONP p ON p.MANDT = a.MANDT AND p.KNUMH = a.KNUMH
             WHERE a.MANDT = '100' AND a.KAPPL = 'TX' AND a.ALAND = 'TR';
  LT_GECERLI = SELECT ORAN FROM KURAL_ORAN
                WHERE GECERLI_BAS = (SELECT MAX(GECERLI_BAS) FROM KURAL_ORAN WHERE GECERLI_BAS <= :IV_GUN);
  LT_V = SELECT v.BELNR, v.GJAHR, v.MWSKZ, v.KTOSL, v.HWBAS, v.HWSTE, b.BLDAT, b.BUDAT, b.XBLNR, o.ORAN,
                b.MUHATAP, b.ULKE, b.YON
           FROM BSET v
           JOIN :LT_ORAN o ON o.MWSKZ = v.MWSKZ
           JOIN TF_BELGELER(:IV_GUN) b ON b.BELNR = v.BELNR AND b.GJAHR = v.GJAHR
          WHERE v.MANDT = '100' AND v.BUKRS = '1000' AND LEFT(b.BUDAT, 6) = :IV_DONEM;
  RETURN
    -- (a) a rate not valid in the period (e.g. the 18% in force before 10 Jul 2023)
    SELECT CAST('K3_GECERSIZ_ORAN' AS NVARCHAR(30)) AS KURAL, CAST('KESIN' AS NVARCHAR(8)) AS GUVEN,
           CAST(CASE WHEN v.KTOSL = 'MWS' THEN 'RISK' ELSE 'FIRSAT' END AS NVARCHAR(6)) AS TUR,
           v.BELNR, v.GJAHR, v.XBLNR, CAST('' AS NVARCHAR(36)) AS ETTN, v.MUHATAP, v.BLDAT AS BELGE_TARIHI,
           v.BUDAT AS KAYIT_TARIHI,
           CASE WHEN v.KTOSL = 'MWS' THEN ROUND(v.HWBAS * e.YENI_ORAN / 100, 2) - v.HWSTE ELSE 0 END AS ETKI_HES,
           CASE WHEN v.KTOSL = 'VST' THEN ROUND(v.HWBAS * e.YENI_ORAN / 100, 2) - v.HWSTE ELSE 0 END AS ETKI_IND,
           TO_DECIMAL(0, 23, 2) AS ETKI_KDV2, v.ORAN AS DEFTER_DEGER, e.YENI_ORAN AS GIB_DEGER,
           CAST(v.MWSKZ AS NVARCHAR(100)) AS DETAY
      FROM :LT_V v
      JOIN KURAL_ESKI_ORAN e ON e.ESKI_ORAN = v.ORAN
     WHERE v.ORAN NOT IN (SELECT ORAN FROM :LT_GECERLI)
    UNION ALL
    -- (b) VAT ≠ base × the code's rate
    SELECT 'K3_HESAP_HATASI', 'KESIN',
           CASE WHEN (v.KTOSL = 'MWS' AND ROUND(v.HWBAS * v.ORAN / 100, 2) > v.HWSTE)
                  OR (v.KTOSL = 'VST' AND ROUND(v.HWBAS * v.ORAN / 100, 2) < v.HWSTE) THEN 'RISK' ELSE 'FIRSAT' END,
           v.BELNR, v.GJAHR, v.XBLNR, '', v.MUHATAP, v.BLDAT, v.BUDAT,
           CASE WHEN v.KTOSL = 'MWS' THEN ROUND(v.HWBAS * v.ORAN / 100, 2) - v.HWSTE ELSE 0 END,
           CASE WHEN v.KTOSL = 'VST' THEN ROUND(v.HWBAS * v.ORAN / 100, 2) - v.HWSTE ELSE 0 END, 0,
           v.HWSTE, ROUND(v.HWBAS * v.ORAN / 100, 2), v.MWSKZ
      FROM :LT_V v
     WHERE ABS(v.HWSTE - ROUND(v.HWBAS * v.ORAN / 100, 2)) > :LV_TOL
    UNION ALL
    -- (c) export exemption on a domestic customer (rate 0, output tax)
    SELECT 'K3_ISTISNA_YURTICI', 'KESIN', 'RISK', v.BELNR, v.GJAHR, v.XBLNR, '', v.MUHATAP, v.BLDAT, v.BUDAT,
           ROUND(v.HWBAS * :LV_GENEL / 100, 2), 0, 0, 0, ROUND(v.HWBAS * :LV_GENEL / 100, 2), v.MWSKZ
      FROM :LT_V v
     WHERE v.KTOSL = 'MWS' AND v.ORAN = 0 AND v.YON = 'GIDEN' AND v.ULKE = 'TR';
END
