-- Today's method: totals only. VAT on valid e-invoices at the tax authority (by invoice date) vs.
-- movements on 191/391 (by posting date, VAT offset excluded). It does not say which document differs.
CREATE FUNCTION TF_TOPLAM_KONTROLU (IV_DONEM NVARCHAR(6), IV_GUN NVARCHAR(8))
RETURNS TABLE (YON NVARCHAR(5), GIB DECIMAL(23,2), DEFTER DECIMAL(23,2), FARK DECIMAL(23,2))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  LT_E = SELECT YON, SUM(KDV_TUTARI) AS GIB FROM GIB_EBELGE
          WHERE DURUM = 'GECERLI' AND LEFT(BELGE_TARIHI, 6) = :IV_DONEM AND BELGE_TARIHI <= :IV_GUN
          GROUP BY YON;
  LT_B = SELECT * FROM TF_BELGELER(:IV_GUN) WHERE LEFT(BUDAT, 6) = :IV_DONEM AND MAHSUP = 0 AND YON <> '';
  LT_D = SELECT YON, SUM(KDV_DEFTER) AS DEFTER FROM :LT_B GROUP BY YON;
  RETURN
    SELECT CAST(d.YON AS NVARCHAR(5)) AS YON, COALESCE(e.GIB, 0) AS GIB, d.DEFTER, COALESCE(e.GIB, 0) - d.DEFTER AS FARK
      FROM :LT_D d LEFT JOIN :LT_E e ON e.YON = d.YON;
END
