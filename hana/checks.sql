-- K1 · e-invoice ↔ ledger
CREATE FUNCTION TF_K1_EBELGE (IV_DONEM NVARCHAR(6), IV_GUN NVARCHAR(8))
RETURNS TABLE (KURAL NVARCHAR(30), GUVEN NVARCHAR(8), TUR NVARCHAR(6), BELNR NVARCHAR(10), GJAHR NVARCHAR(4),
               XBLNR NVARCHAR(16), ETTN NVARCHAR(36), MUHATAP NVARCHAR(10), BELGE_TARIHI NVARCHAR(8),
               KAYIT_TARIHI NVARCHAR(8), ETKI_HES DECIMAL(23,2), ETKI_IND DECIMAL(23,2), ETKI_KDV2 DECIMAL(23,2),
               DEFTER_DEGER DECIMAL(23,2), GIB_DEGER DECIMAL(23,2), DETAY NVARCHAR(100))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  DECLARE LV_TOL DECIMAL(23,2);
  SELECT DEGER INTO LV_TOL FROM KURAL_PARAMETRE WHERE AD = 'TOLERANS_TL';
  LT_B = SELECT * FROM TF_BELGELER(:IV_GUN);
  LT_E = SELECT e.ETTN, e.BELGE_NO, e.YON, e.DURUM, e.BELGE_TARIHI, e.KDV_TUTARI,
                CASE WHEN e.YON = 'GIDEN' THEN e.ALICI_UNVAN ELSE e.GONDEREN_UNVAN END AS UNVAN,
                COALESCE(m.KUNNR, l.LIFNR, '') AS MUHATAP
           FROM GIB_EBELGE e
           LEFT JOIN KNA1 m ON m.MANDT = '100' AND e.YON = 'GIDEN' AND e.ALICI_VKN <> '' AND m.STCD2 = e.ALICI_VKN
           LEFT JOIN LFA1 l ON l.MANDT = '100' AND e.YON = 'GELEN' AND l.STCD2 = e.GONDEREN_VKN
          WHERE e.BELGE_TARIHI <= :IV_GUN;
  LT_DEFTER_NO = SELECT DISTINCT YON, XBLNR FROM :LT_B WHERE XBLNR <> '';
  LT_GIB_NO = SELECT DISTINCT YON, BELGE_NO FROM :LT_E;
  RETURN
    -- (a) outgoing, valid, not in the ledger: output VAT missing
    SELECT CAST('K1_SATIS_KAYITSIZ' AS NVARCHAR(30)) AS KURAL, CAST('KESIN' AS NVARCHAR(8)) AS GUVEN,
           CAST('RISK' AS NVARCHAR(6)) AS TUR, CAST('' AS NVARCHAR(10)) AS BELNR, CAST('' AS NVARCHAR(4)) AS GJAHR,
           e.BELGE_NO AS XBLNR, e.ETTN, e.MUHATAP, e.BELGE_TARIHI, CAST('' AS NVARCHAR(8)) AS KAYIT_TARIHI,
           e.KDV_TUTARI AS ETKI_HES, TO_DECIMAL(0, 23, 2) AS ETKI_IND, TO_DECIMAL(0, 23, 2) AS ETKI_KDV2,
           TO_DECIMAL(0, 23, 2) AS DEFTER_DEGER, e.KDV_TUTARI AS GIB_DEGER, CAST(e.UNVAN AS NVARCHAR(100)) AS DETAY
      FROM :LT_E e
      LEFT JOIN :LT_DEFTER_NO d ON d.YON = 'GIDEN' AND d.XBLNR = e.BELGE_NO
     WHERE e.YON = 'GIDEN' AND e.DURUM = 'GECERLI' AND LEFT(e.BELGE_TARIHI, 6) = :IV_DONEM AND d.XBLNR IS NULL
    UNION ALL
    -- (b) incoming, valid, not in the ledger: deduction missed
    SELECT 'K1_ALIS_KAYITSIZ', 'KESIN', 'FIRSAT', '', '', e.BELGE_NO, e.ETTN, e.MUHATAP, e.BELGE_TARIHI, '',
           0, e.KDV_TUTARI, 0, 0, e.KDV_TUTARI, e.UNVAN
      FROM :LT_E e
      LEFT JOIN :LT_DEFTER_NO d ON d.YON = 'GELEN' AND d.XBLNR = e.BELGE_NO
     WHERE e.YON = 'GELEN' AND e.DURUM = 'GECERLI' AND LEFT(e.BELGE_TARIHI, 6) = :IV_DONEM AND d.XBLNR IS NULL
    UNION ALL
    -- (c) in the ledger (domestic purchase), not at the tax authority: unsupported deduction
    SELECT 'K1_GIB_YOK', 'KESIN', 'RISK', b.BELNR, b.GJAHR, b.XBLNR, '', b.MUHATAP, b.BLDAT, b.BUDAT,
           0, -b.IND, 0, b.KDV_DEFTER, 0, ''
      FROM :LT_B b
      LEFT JOIN :LT_GIB_NO g ON g.YON = 'GELEN' AND g.BELGE_NO = b.XBLNR
     WHERE b.YON = 'GELEN' AND b.ULKE IN ('TR', '') AND LEFT(b.BUDAT, 6) = :IV_DONEM AND b.KDV_DEFTER > 0
       AND g.BELGE_NO IS NULL
    UNION ALL
    -- (d) VAT differs within a matched pair: 191/391 amount in the ledger vs. the e-invoice
    SELECT 'K1_TUTAR_FARKI', 'KESIN',
           CASE WHEN (b.YON = 'GELEN' AND e.KDV_TUTARI < b.KDV_DEFTER) OR (b.YON = 'GIDEN' AND e.KDV_TUTARI > b.KDV_DEFTER)
                THEN 'RISK' ELSE 'FIRSAT' END,
           b.BELNR, b.GJAHR, b.XBLNR, e.ETTN, b.MUHATAP, b.BLDAT, b.BUDAT,
           CASE WHEN b.YON = 'GIDEN' THEN e.KDV_TUTARI - b.HES ELSE 0 END,
           CASE WHEN b.YON = 'GELEN' THEN e.KDV_TUTARI - b.IND ELSE 0 END, 0,
           b.KDV_DEFTER, e.KDV_TUTARI, ''
      FROM :LT_B b
      JOIN :LT_E e ON e.YON = b.YON AND e.BELGE_NO = b.XBLNR AND e.DURUM <> 'RED'
     WHERE LEFT(b.BUDAT, 6) = :IV_DONEM AND ABS(e.KDV_TUTARI - b.KDV_DEFTER) > :LV_TOL
    UNION ALL
    -- (e) rejected e-invoice in the ledger
    SELECT 'K1_REDDEDILMIS', 'KESIN', 'RISK', b.BELNR, b.GJAHR, b.XBLNR, e.ETTN, b.MUHATAP, b.BLDAT, b.BUDAT,
           0, -b.IND, 0, b.KDV_DEFTER, e.KDV_TUTARI, ''
      FROM :LT_B b
      JOIN :LT_E e ON e.YON = 'GELEN' AND e.BELGE_NO = b.XBLNR AND e.DURUM = 'RED'
     WHERE b.YON = 'GELEN' AND LEFT(b.BUDAT, 6) = :IV_DONEM;
END
