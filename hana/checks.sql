-- K4 · VAT withholding. Type from the vendor's industry (LFA1.BRSCH → KURAL_TEVKIFAT); buyer scope from SIRKET_VERGI;
-- threshold by invoice year from KURAL_SINIR (VAT included; above it, on the full amount).
CREATE FUNCTION TF_K4_TEVKIFAT (IV_DONEM NVARCHAR(6), IV_GUN NVARCHAR(8))
RETURNS TABLE (KURAL NVARCHAR(30), GUVEN NVARCHAR(8), TUR NVARCHAR(6), BELNR NVARCHAR(10), GJAHR NVARCHAR(4),
               XBLNR NVARCHAR(16), ETTN NVARCHAR(36), MUHATAP NVARCHAR(10), BELGE_TARIHI NVARCHAR(8),
               KAYIT_TARIHI NVARCHAR(8), ETKI_HES DECIMAL(23,2), ETKI_IND DECIMAL(23,2), ETKI_KDV2 DECIMAL(23,2),
               DEFTER_DEGER DECIMAL(23,2), GIB_DEGER DECIMAL(23,2), DETAY NVARCHAR(100))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  DECLARE LV_TOL DECIMAL(23,2);
  DECLARE LV_GUN INTEGER;
  SELECT DEGER INTO LV_TOL FROM KURAL_PARAMETRE WHERE AD = 'TOLERANS_TL';
  SELECT TO_INT(DEGER) INTO LV_GUN FROM KURAL_PARAMETRE WHERE AD = 'BOLUNMUS_GUN';
  LT_B = SELECT b.BELNR, b.GJAHR, b.XBLNR, b.MUHATAP, b.BLDAT, b.BUDAT, b.IND, b.TEV_KODU, b.TEV_TUTAR,
                t.TEVKIFAT_KODU, t.WT_WITHCD AS BEKLENEN, s.SINIR_KDV_DAHIL AS SINIR,
                b.MATRAH + b.IND AS BRUT, ROUND(b.IND * t.PAY / t.PAYDA, 2) AS BEKLENEN_TUTAR
           FROM TF_BELGELER(:IV_GUN) b
           JOIN KURAL_TEVKIFAT t ON t.NACE = b.NACE
           JOIN SIRKET_VERGI c ON c.BUKRS = '1000'
           JOIN KURAL_SINIR s ON s.YIL = LEFT(b.BLDAT, 4)
          WHERE b.YON = 'GELEN' AND b.ULKE = 'TR' AND b.IND > 0
            AND ((t.ALICI = 'KDV_MUKELLEFI' AND c.KDV_MUKELLEFI = 'X')
              OR (t.ALICI = 'BELIRLENMIS_ALICI' AND c.BELIRLENMIS_ALICI = 'X'));
  LT_KUCUK = SELECT * FROM :LT_B WHERE BRUT <= SINIR AND TEV_KODU = '';
  RETURN
    -- (a) in scope, above the threshold, no withholding
    SELECT CAST('K4_TEVKIFAT_YOK' AS NVARCHAR(30)) AS KURAL, CAST('KESIN' AS NVARCHAR(8)) AS GUVEN,
           CAST('RISK' AS NVARCHAR(6)) AS TUR, b.BELNR, b.GJAHR, b.XBLNR, CAST('' AS NVARCHAR(36)) AS ETTN,
           b.MUHATAP, b.BLDAT AS BELGE_TARIHI, b.BUDAT AS KAYIT_TARIHI, TO_DECIMAL(0, 23, 2) AS ETKI_HES,
           TO_DECIMAL(0, 23, 2) AS ETKI_IND, b.BEKLENEN_TUTAR AS ETKI_KDV2, TO_DECIMAL(0, 23, 2) AS DEFTER_DEGER,
           b.BEKLENEN_TUTAR AS GIB_DEGER, CAST(b.TEVKIFAT_KODU AS NVARCHAR(100)) AS DETAY
      FROM :LT_B b
     WHERE LEFT(b.BUDAT, 6) = :IV_DONEM AND b.BRUT > b.SINIR AND b.TEV_KODU = ''
    UNION ALL
    -- (b) withholding present but code or amount wrong
    SELECT 'K4_TEVKIFAT_ORAN', 'KESIN', CASE WHEN b.BEKLENEN_TUTAR > b.TEV_TUTAR THEN 'RISK' ELSE 'FIRSAT' END,
           b.BELNR, b.GJAHR, b.XBLNR, '', b.MUHATAP, b.BLDAT, b.BUDAT, 0, 0, b.BEKLENEN_TUTAR - b.TEV_TUTAR,
           b.TEV_TUTAR, b.BEKLENEN_TUTAR, b.TEV_KODU || '>' || b.BEKLENEN
      FROM :LT_B b
     WHERE LEFT(b.BUDAT, 6) = :IV_DONEM AND b.TEV_KODU <> ''
       AND (b.TEV_KODU <> b.BEKLENEN OR ABS(b.TEV_TUTAR - b.BEKLENEN_TUTAR) > :LV_TOL)
    UNION ALL
    -- (c) same day, same vendor, each under the threshold, together above it: possibly split
    SELECT DISTINCT 'K4_BOLUNMUS', 'MUHTEMEL', 'RISK', x.BELNR, x.GJAHR, x.XBLNR, '', x.MUHATAP, x.BLDAT, x.BUDAT,
           0, 0, x.BEKLENEN_TUTAR, 0, x.BEKLENEN_TUTAR, MIN(y.BELNR) OVER (PARTITION BY x.BELNR, x.GJAHR)
      FROM :LT_KUCUK x
      JOIN :LT_KUCUK y ON y.MUHATAP = x.MUHATAP AND (y.BELNR <> x.BELNR OR y.GJAHR <> x.GJAHR)
                      AND ABS(DAYS_BETWEEN(TO_DATE(y.BLDAT, 'YYYYMMDD'), TO_DATE(x.BLDAT, 'YYYYMMDD'))) <= :LV_GUN
                      AND x.BRUT + y.BRUT > x.SINIR
     WHERE LEFT(x.BUDAT, 6) = :IV_DONEM;
END
