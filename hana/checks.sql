-- Return lines, month by month (posting month): from the tax lines, like SAP's advance VAT return (S_ALR_87012357).
-- The carried-forward VAT chain is built in the engine (Python).
CREATE FUNCTION TF_BEYANNAME_AYLIK (IV_GUN NVARCHAR(8))
RETURNS TABLE (DONEM NVARCHAR(6), MATRAH DECIMAL(23,2), HESAPLANAN DECIMAL(23,2), ISTISNA_MATRAH DECIMAL(23,2),
               INDIRILECEK DECIMAL(23,2), SORUMLU DECIMAL(23,2))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  LT_V = SELECT LEFT(k.BUDAT, 6) AS DONEM,
                SUM(CASE WHEN v.KTOSL = 'MWS' AND v.HWSTE <> 0 THEN v.HWBAS ELSE 0 END) AS MATRAH,
                SUM(CASE WHEN v.KTOSL = 'MWS' THEN CASE v.SHKZG WHEN 'H' THEN v.HWSTE ELSE -v.HWSTE END ELSE 0 END) AS HESAPLANAN,
                SUM(CASE WHEN v.KTOSL = 'MWS' AND v.HWSTE = 0 THEN v.HWBAS ELSE 0 END) AS ISTISNA_MATRAH,
                SUM(CASE WHEN v.KTOSL = 'VST' THEN CASE v.SHKZG WHEN 'S' THEN v.HWSTE ELSE -v.HWSTE END ELSE 0 END) AS INDIRILECEK
           FROM BSET v
           JOIN BKPF k ON k.MANDT = v.MANDT AND k.BUKRS = v.BUKRS AND k.BELNR = v.BELNR AND k.GJAHR = v.GJAHR
          WHERE v.MANDT = '100' AND v.BUKRS = '1000' AND k.BUDAT <= :IV_GUN
          GROUP BY LEFT(k.BUDAT, 6);
  LT_W = SELECT LEFT(k.BUDAT, 6) AS DONEM, SUM(w.WT_QBSHH) AS SORUMLU
           FROM WITH_ITEM w
           JOIN BKPF k ON k.MANDT = w.MANDT AND k.BUKRS = w.BUKRS AND k.BELNR = w.BELNR AND k.GJAHR = w.GJAHR
          WHERE w.MANDT = '100' AND w.BUKRS = '1000' AND w.WITHT = 'KT' AND k.BUDAT <= :IV_GUN
          GROUP BY LEFT(k.BUDAT, 6);
  RETURN
    SELECT v.DONEM, v.MATRAH, v.HESAPLANAN, v.ISTISNA_MATRAH, v.INDIRILECEK, COALESCE(w.SORUMLU, 0) AS SORUMLU
      FROM :LT_V v LEFT JOIN :LT_W w ON w.DONEM = v.DONEM;
END
